    private void btnProcessActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnProcessActionPerformed
        String customerName = txtCustomerName.getText();

String productName = cmbProduct.getSelectedItem().toString();

double price = Double.parseDouble(txtPrice.getText());

// Create calculation object
ProductCalculations calc = new ProductCalculations(price);

// Calculate VAT, commission and total
double vat = calc.GetVat();

double commission = calc.GetCommission();

double total = calc.GetTotal();

// Display results
javax.swing.JOptionPane.showMessageDialog(this,
        "Customer Name: " + customerName
        + "\nProduct: " + productName
        + "\nVAT: R " + vat
        + "\nCOMMISSION: R " + commission
        + "\nTOTAL: R " + total);


try {

    java.io.PrintWriter writer = new java.io.PrintWriter(
            new java.io.FileWriter("data.txt", true));

    writer.println("DATA LOG");
    writer.println("**************************************");
    writer.println("Customer Name: " + customerName);
    writer.println("Product: " + productName);
    writer.println("VAT: R " + vat);
    writer.println("COMMISSION: R " + commission);
    writer.println("TOTAL: R " + total);
    writer.println("**************************************");
    writer.println();

    writer.close();

    javax.swing.JOptionPane.showMessageDialog(this,
            "Sales information saved successfully!");

} catch (java.io.IOException e) {

    javax.swing.JOptionPane.showMessageDialog(this,
            "Error saving file: " + e.getMessage());

}
    }//GEN-LAST:event_btnProcessActionPerformed

